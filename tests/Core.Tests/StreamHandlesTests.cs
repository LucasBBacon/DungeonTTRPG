using System.Text;
using Dungeon.Core.Content;
using Dungeon.Sim.Tools;
using Xunit;

namespace Dungeon.Core.Tests;

/// <summary>
/// The generated stream handles (<c>StreamHandles.g.cs</c>): drift-tested against <c>registry/streams.json</c>,
/// equal to <see cref="StreamRegistry.KeyOf"/> for every row, and to the SV 4.1 vectors (Review Focus 1, 2).
/// </summary>
public class StreamHandlesTests
{
    private const string Regenerate = "run `dotnet run --project src/Sim -- stream-handles`";
    private const ulong Rs = 0x0123456789ABCDEFUL;

    private static readonly Lazy<ContentSet> Repository = new(() =>
        ContentLoader.Load(ContentDirectory.Read(Path.Combine(RepoRoot.Find(), "content"))));

    // --- Drift ---

    [Fact]
    public void Committed_handles_match_the_registry()
    {
        var committed = File.ReadAllBytes(Path.Combine(RepoRoot.Find(), "src", "Core", "Random", "StreamHandles.g.cs"));

        Assert.True(
            StreamHandlesWriter.Write(Repository.Value) == new UTF8Encoding(false, throwOnInvalidBytes: true).GetString(committed),
            $"StreamHandles.g.cs is stale: {Regenerate}.");
    }

    [Fact]
    public void Generated_file_text_is_lf_with_a_trailing_newline()
    {
        string text = StreamHandlesWriter.Write(Repository.Value);

        Assert.StartsWith("// <auto-generated/>\n", text, StringComparison.Ordinal);
        Assert.DoesNotContain("\r", text, StringComparison.Ordinal);
        Assert.DoesNotContain("unchecked", text, StringComparison.Ordinal);
        Assert.EndsWith("}\n", text, StringComparison.Ordinal);
    }

    // --- Review Focus 1: the SV 4.1 vectors through handles ---

    [Fact]
    public void Sv41_vectors_through_handles()
    {
        var dungeon = Streams.Dungeon(Rs);
        Assert.Equal(0x99b0558c8449420fUL, dungeon.Value);
        Assert.Equal(0x8224e58417674634UL, dungeon.Floor(1).Value);
        Assert.Equal(0x408b2970acba60f5UL, dungeon.Floor(1).Attempt(0).Value);

        var layout = dungeon.Floor(1).Attempt(0).Layout;
        Assert.Equal(0xffc7031c11fad2b3UL, layout.Value);
        Assert.Equal("dungeon/floor/{N}/attempt/{a}/layout", layout.Handle.RowId);
        Assert.Equal(layout.Value, layout.Handle.Key);

        Assert.Equal(0xb8e7d03a7635ebcaUL, dungeon.Floor(1).Checks.Value);
        Assert.Equal(0xab0885a7f33fd7adUL, dungeon.Floor(1).Checks.HNotice("unit.hero", "unit.mastiff.1", 0, 0));
    }

    [Fact]
    public void Run_streams_keys_come_from_the_handles()
    {
        Assert.Equal(KeyAlgebra.Derive(7, "combat"), Streams.Combat(7).Value);
        Assert.Equal(KeyAlgebra.Derive(KeyAlgebra.Derive(7, "loot"), "shrine"), Streams.Loot(7).Shrine.Value);
        Assert.Equal("combat", Streams.Combat(7).Handle.RowId);
        Assert.Equal("loot/shrine", Streams.Loot(7).Shrine.Handle.RowId);
    }

    // --- Review Focus 1: every handle equals the registry derivation ---

    [Fact]
    public void Every_handle_equals_the_registry_derivation()
    {
        var set = Repository.Value;
        var nonDomain = set.All<StreamRow>()
            .Where(r => !StreamRegistry.IsDomain(set, r))
            .Select(r => r.Id)
            .Order(StringComparer.Ordinal)
            .ToArray();
        Assert.Equal(nonDomain, StreamHandleIndex.All.Select(e => e.RowId).ToArray());

        foreach (var (rowId, key) in StreamHandleIndex.All)
        {
            var (values, numbers, texts) = SampleIndices(set, rowId);
            Assert.True(
                StreamRegistry.KeyOf(set, rowId, Rs, values) == key(Rs, numbers, texts),
                $"{rowId}: the handle's key differs from StreamRegistry.KeyOf.");
        }
    }

    [Fact]
    public void Domain_methods_hash_the_parent_key()
    {
        var set = Repository.Value;
        var route = Streams.Dungeon(Rs).Route;
        Assert.Equal(StreamRegistry.KeyOf(set, "dungeon/route", Rs, []), route.Value);
        Assert.Equal(KeyAlgebra.H(route.Value, "themePerm", KeyAlgebra.LabelId("theme.crypt")), route.ThemePerm("theme.crypt"));
        Assert.Equal(
            KeyAlgebra.H(route.Value, "bossOrder", KeyAlgebra.LabelId("theme.crypt"), 2, KeyAlgebra.LabelId("boss.warden")),
            route.BossOrder("theme.crypt", 2, "boss.warden"));

        Assert.Equal(KeyAlgebra.H(route.Value, "finalOrder", KeyAlgebra.LabelId("boss.warden")), route.FinalOrder("boss.warden"));
        Assert.Equal(KeyAlgebra.H(route.Value, "omen", KeyAlgebra.LabelId("theme.crypt")), route.Omen("theme.crypt"));

        var checks = Streams.Dungeon(Rs).Floor(1).Checks;
        Assert.Equal(StreamRegistry.KeyOf(set, "dungeon/floor/{N}/checks", Rs, [new(1, null)]), checks.Value);
        Assert.Equal(KeyAlgebra.H(checks.Value, "h:steal", KeyAlgebra.LabelId("unit.hero"), 3, 1), checks.HSteal("unit.hero", 3, 1));
        Assert.Equal(
            KeyAlgebra.H(checks.Value, "h:object", KeyAlgebra.LabelId("object.chest"), KeyAlgebra.LabelId("check.lock"), 2, 1),
            checks.HObject("object.chest", "check.lock", 2, 1));
        Assert.Equal(
            KeyAlgebra.H(checks.Value, "h:save", KeyAlgebra.LabelId("object.spring"), KeyAlgebra.LabelId("unit.hero"), 4, 0),
            checks.HSave("object.spring", "unit.hero", 4, 0));
        Assert.Equal(
            KeyAlgebra.H(checks.Value, "h:lurkStealth", KeyAlgebra.LabelId("group.lurkers"), 5, KeyAlgebra.LabelId("band.6"), 1),
            checks.HLurkStealth("group.lurkers", 5, "band.6", 1));
    }

    [Fact]
    public void Every_domain_equals_the_registry_derivation()
    {
        var set = Repository.Value;
        var domains = set.All<StreamRow>()
            .Where(r => StreamRegistry.IsDomain(set, r))
            .Select(r => r.Id)
            .Order(StringComparer.Ordinal)
            .ToArray();
        Assert.NotEmpty(domains);
        Assert.Equal(domains, StreamHandleIndex.Domains.Select(e => e.RowId).ToArray());

        foreach (var (rowId, h) in StreamHandleIndex.Domains)
        {
            var (values, numbers, texts) = SampleIndices(set, rowId);
            Assert.True(
                KeyAlgebra.Draw(StreamRegistry.KeyOf(set, rowId, Rs, values), 0) == h(Rs, numbers, texts),
                $"{rowId}: the handle's H differs from Draw(StreamRegistry.KeyOf, 0).");
        }
    }

    [Fact]
    public void Keys_and_handles_cannot_be_built_or_rekeyed_from_outside_the_generated_chain()
    {
        var keys = KeyTypes();
        Assert.NotEmpty(keys);
        foreach (var type in keys.Append(typeof(StreamHandle)))
        {
            Assert.True(
                type.GetConstructors().All(c => c.GetParameters().Length == 0),
                $"{type.Name} has a public constructor taking a key.");
            foreach (var property in type.GetProperties())
            {
                Assert.True(property.SetMethod is null, $"{type.Name}.{property.Name} can be set or init (a with expression could rekey it).");
            }
        }
    }

    // --- Review Focus 2: arity and index type ---

    [Fact]
    public void A_label_id_index_is_absorbed_as_its_label_id()
    {
        var set = Repository.Value;
        ulong viaText = StreamRegistry.KeyOf(set, "dungeon/route/themePerm/{themeId:}", Rs, [new(0, "theme.crypt")]);
        ulong route = StreamRegistry.KeyOf(set, "dungeon/route", Rs, []);

        Assert.Equal(KeyAlgebra.Derive(route, "themePerm", KeyAlgebra.LabelId("theme.crypt")), viaText);
    }

    [Fact]
    public void Key_of_refuses_mismatched_indices()
    {
        var set = Repository.Value;
        const string floor = "dungeon/floor/{N}";

        Assert.Throws<ArgumentException>(() => StreamRegistry.KeyOf(set, floor, Rs, []));
        Assert.Throws<ArgumentException>(() => StreamRegistry.KeyOf(set, floor, Rs, [new(1, null), new(2, null)]));
        Assert.Throws<ArgumentException>(() => StreamRegistry.KeyOf(set, floor, Rs, [new(0, "a.b")]));
        Assert.Throws<ArgumentException>(() => StreamRegistry.KeyOf(set, "dungeon/route/themePerm/{themeId:}", Rs, [new(0, null)]));
        Assert.Throws<ArgumentException>(() => StreamRegistry.KeyOf(set, "no/such/row", Rs, []));
    }

    [Fact]
    public void Key_of_zero_extends_a_uint_and_refuses_one_above_its_range()
    {
        var set = ContentLoader.Load([new ContentFile("registry/streams.json", """
            {"streams": [{"path": "r/{u}", "alias": [], "parent": null, "label": "r", "indices": [{"name": "u", "type": "uint"}],
              "class": "node", "stage": null, "readers": [], "consumers": [], "retryScope": "never", "rules": [],
              "keyType": "core", "owner": "MAIN", "source": [], "wave": "M1"}]}
            """)]);

        Assert.Equal(KeyAlgebra.Derive(Rs, "r", uint.MaxValue), StreamRegistry.KeyOf(set, "r/{u}", Rs, [new(uint.MaxValue, null)]));
        Assert.Throws<ArgumentException>(() => StreamRegistry.KeyOf(set, "r/{u}", Rs, [new((ulong)uint.MaxValue + 1, null)]));
    }

    [Fact]
    public void Handles_expose_no_signed_parameter()
    {
        var signed = new[] { typeof(sbyte), typeof(short), typeof(int), typeof(long), typeof(nint) };
        var generated = typeof(Streams).Assembly.GetTypes()
            .Where(t => t == typeof(Streams) || t.IsDefined(typeof(StreamKeyAttribute), inherit: false));
        foreach (var type in generated)
        {
            foreach (var method in type.GetMethods(System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.Instance | System.Reflection.BindingFlags.Static | System.Reflection.BindingFlags.DeclaredOnly))
            {
                foreach (var p in method.GetParameters())
                {
                    Assert.False(signed.Contains(p.ParameterType), $"{type.Name}.{method.Name}({p.Name}) is signed.");
                }
            }
        }
    }

    [Fact]
    public void Run_streams_open_through_the_handles_at_counter_0()
    {
        var streams = RunStreams.FromSeed(7);
        Assert.Equal(new DrawStream(Streams.Combat(7).Value, 0), streams.Combat);
        Assert.Equal(new DrawStream(Streams.Loot(7).Shrine.Value, 0), streams.Shrine);
        Assert.Equal(Streams.Combat(7).Open(), streams.Combat);
        Assert.Equal(Streams.Loot(7).Shrine.Open(), streams.Shrine);
    }

    [Fact]
    public void Exactly_the_drawn_from_keys_have_open_and_it_opens_their_key_at_counter_0()
    {
        var keys = KeyTypes();
        Assert.NotEmpty(keys);
        int drawn = 0;
        foreach (var type in keys)
        {
            var handle = type.GetProperty("Handle");
            var open = type.GetMethod("Open", Type.EmptyTypes);
            Assert.True((handle is null) == (open is null), $"{type.Name}: Handle and Open() must come together.");
            if (open is null)
            {
                continue;
            }

            drawn++;
            Assert.Equal(typeof(DrawStream), open.ReturnType);
            object key = KeyConstructor(type).Invoke([0x5EEDUL]);
            Assert.Equal(new DrawStream(0x5EEDUL, 0), (DrawStream)open.Invoke(key, null)!);
        }

        int expected = Repository.Value.All<StreamRow>()
            .Count(r => !StreamRegistry.IsDomain(Repository.Value, r) && r.Class is not (CountClass.Node or CountClass.Keyed));
        Assert.Equal(expected, drawn);
    }

    /// <summary>The generated key structs: value types in <c>Dungeon.Core</c> named <c>*Key</c> with a <c>ulong Value</c>.</summary>
    private static List<Type> KeyTypes() =>
        typeof(Streams).Assembly.GetTypes()
            .Where(t => t.IsValueType && t.Namespace == "Dungeon.Core" && t.Name.EndsWith("Key", StringComparison.Ordinal)
                && t.GetProperty("Value")?.PropertyType == typeof(ulong))
            .ToList();

    private static System.Reflection.ConstructorInfo KeyConstructor(Type type) =>
        type.GetConstructor(System.Reflection.BindingFlags.Instance | System.Reflection.BindingFlags.NonPublic, [typeof(ulong)])
            ?? throw new InvalidOperationException($"{type.Name} has no internal (ulong) constructor.");

    /// <summary>
    /// Sample indices for every index along <paramref name="rowId"/>'s parent chain, root first: numbers 1, 2, 3…
    /// and a distinct text <c>"text.0"</c>, <c>"text.1"</c>… for each <c>labelId</c>, so a swapped part order shows.
    /// </summary>
    private static (StreamIndexValue[] Values, ulong[] Numbers, string[] Texts) SampleIndices(ContentSet set, string rowId)
    {
        var chain = new List<StreamRow>();
        for (string? id = rowId; id is not null; id = chain[^1].Parent)
        {
            chain.Add(set.Find<StreamRow>(id) ?? throw new InvalidOperationException(id));
        }

        chain.Reverse();
        var values = new List<StreamIndexValue>();
        var numbers = new List<ulong>();
        var texts = new List<string>();
        foreach (var index in chain.SelectMany(r => r.Indices))
        {
            if (index.Type == IndexType.LabelId)
            {
                string text = "text." + texts.Count.ToString(System.Globalization.CultureInfo.InvariantCulture);
                values.Add(new StreamIndexValue(0, text));
                texts.Add(text);
            }
            else
            {
                ulong n = (ulong)numbers.Count + 1;
                values.Add(new StreamIndexValue(n, null));
                numbers.Add(n);
            }
        }

        return (values.ToArray(), numbers.ToArray(), texts.ToArray());
    }
}
