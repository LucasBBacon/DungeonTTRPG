using System.Text;
using Dungeon.Core.Content;
using Dungeon.Sim.Tools;
using Xunit;

namespace Dungeon.Core.Tests;

/// <summary>
/// The three content hashes (SV 4.6, owner ruling 4): independent of file order and line endings,
/// split by field tag, and embedded in the build as <c>ContentHashes.g.cs</c>.
/// </summary>
public class ContentHashTests
{
    private const string Regenerate = "run `dotnet run --project src/Sim -- content-hashes`";

    // --- Review Focus 2: order independence ---

    [Fact]
    public void Reversed_file_order_and_crlf_give_equal_hashes()
    {
        var files = ReadRepositoryContent();
        var reversed = files
            .Reverse()
            .Select(f => f with { Text = f.Text.Replace("\r\n", "\n").Replace("\n", "\r\n") })
            .ToArray();

        Assert.Equal(ContentHashing.Compute(ContentLoader.Load(files)), ContentHashing.Compute(ContentLoader.Load(reversed)));
        Assert.Equal(ContentHashing.Compute(Fixture()), ContentHashing.Compute(Fixture(reversed: true, crlf: true)));
    }

    // --- Field tags ---

    [Fact]
    public void Editing_a_display_field_changes_only_the_display_hash()
    {
        var before = ContentHashing.Compute(Fixture());
        var after = ContentHashing.Compute(Fixture(text: "Hello there"));

        Assert.NotEqual(before.Display, after.Display);
        Assert.Equal(before.Manifest, after.Manifest);
        Assert.Equal(before.GenContent, after.GenContent);
    }

    [Fact]
    public void Editing_a_rules_field_changes_only_the_manifest_hash()
    {
        var before = ContentHashing.Compute(Fixture());
        var after = ContentHashing.Compute(Fixture(owner: "RS"));

        Assert.NotEqual(before.Manifest, after.Manifest);
        Assert.Equal(before.Display, after.Display);
        Assert.Equal(before.GenContent, after.GenContent);
    }

    [Fact]
    public void No_kind_is_read_by_generation_yet()
    {
        Assert.DoesNotContain(ContentKinds.All, k => k.ReadByGeneration);

        // Plan call 6: the digest of the empty manifest, whatever the content.
        Assert.Equal(
            ContentHashing.Compute(ContentLoader.Load([])).GenContent,
            ContentHashing.Compute(ContentLoader.Load(ReadRepositoryContent())).GenContent);
    }

    // --- Drift guard ---

    [Fact]
    public void Embedded_hashes_match_content()
    {
        var hashes = ContentHashing.Compute(ContentLoader.Load(ReadRepositoryContent()));

        Assert.True(hashes.Manifest.ToHex() == ContentHashes.Manifest, $"content/ changed (manifestHash): {Regenerate}.");
        Assert.True(hashes.Display.ToHex() == ContentHashes.Display, $"content/ changed (displayHash): {Regenerate}.");
        Assert.True(hashes.GenContent.ToHex() == ContentHashes.GenContent, $"content/ changed (genContentHash): {Regenerate}.");
    }

    [Fact]
    public void Generator_output_matches_the_committed_file()
    {
        var hashes = ContentHashing.Compute(ContentLoader.Load(ReadRepositoryContent()));
        var committed = File.ReadAllBytes(Path.Combine(RepoRoot.Find(), "src", "Core", "Content", "ContentHashes.g.cs"));

        Assert.True(
            ContentHashesWriter.Write(hashes) == new UTF8Encoding(false, throwOnInvalidBytes: true).GetString(committed),
            $"ContentHashes.g.cs is stale: {Regenerate}.");
    }

    [Fact]
    public void Generated_file_text_is_lf_with_a_trailing_newline()
    {
        string text = ContentHashesWriter.Write(ContentHashing.Compute(Fixture()));

        Assert.StartsWith("// <auto-generated/>\n", text, StringComparison.Ordinal);
        Assert.DoesNotContain("\r", text, StringComparison.Ordinal);
        Assert.EndsWith("}\n", text, StringComparison.Ordinal);
    }

    /// <summary>A check file and a strings file, with one rules field and one display field to edit.</summary>
    private static ContentSet Fixture(string owner = "MAIN", string text = "Hello", bool reversed = false, bool crlf = false)
    {
        string checks = $$"""
            {
              "checks": [
                {
                  "id": "V19.ClassDeclared",
                  "owner": "{{owner}}",
                  "phase": "s",
                  "deps": [],
                  "uses": [],
                  "class": "build",
                  "action": "fail the build",
                  "wave": "M1",
                  "ciTier": "pr"
                }
              ]
            }
            """;
        string strings = $$"""
            {
              "strings": [
                { "key": "naming.label.hello", "text": "{{text}}", "field": "label" }
              ]
            }
            """;
        var files = new[] { new ContentFile("registry/checks.json", checks), new ContentFile("strings/en.json", strings) };
        if (reversed)
        {
            Array.Reverse(files);
        }

        if (crlf)
        {
            files = files.Select(f => f with { Text = f.Text.Replace("\n", "\r\n") }).ToArray();
        }

        return ContentLoader.Load(files);
    }

    /// <summary>The repository's <c>content/</c>, read exactly as the content-hashes command reads it.</summary>
    private static ContentFile[] ReadRepositoryContent() => ContentDirectory.Read(Path.Combine(RepoRoot.Find(), "content"));
}
