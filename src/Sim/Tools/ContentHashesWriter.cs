using System.Text;
using Dungeon.Core.Content;

namespace Dungeon.Sim.Tools;

/// <summary>
/// Writes <c>src/Core/Content/ContentHashes.g.cs</c>, the content hashes embedded in the build (SV 4.6,
/// owner ruling 4). Run <c>dotnet run --project src/Sim -- content-hashes</c> after every content edit;
/// <c>ContentHashTests</c> fails until the file matches <c>content/</c>.
/// </summary>
public static class ContentHashesWriter
{
    /// <summary>The exact file text for <paramref name="hashes"/>: LF line endings and a trailing newline.</summary>
    public static string Write(ContentHashSet hashes)
    {
        var sb = new StringBuilder();
        Line(sb, "// <auto-generated/>");
        Line(sb, "// Written by `dotnet run --project src/Sim -- content-hashes` from content/. Do not edit.");
        Line(sb, "");
        Line(sb, "namespace Dungeon.Core.Content;");
        Line(sb, "");
        Line(sb, "/// <summary>The content hashes of SV 4.6, computed in the build pipeline over content/ (64 hex digits each).</summary>");
        Line(sb, "public static class ContentHashes");
        Line(sb, "{");
        Line(sb, "    /// <summary><c>manifestHash</c>: every record's rules fields.</summary>");
        Line(sb, $"    public const string Manifest = \"{hashes.Manifest.ToHex()}\";");
        Line(sb, "");
        Line(sb, "    /// <summary><c>displayHash</c>: the display-tagged fields.</summary>");
        Line(sb, $"    public const string Display = \"{hashes.Display.ToHex()}\";");
        Line(sb, "");
        Line(sb, "    /// <summary><c>genContentHash</c>: the subset of the manifest that generation reads.</summary>");
        Line(sb, $"    public const string GenContent = \"{hashes.GenContent.ToHex()}\";");
        Line(sb, "}");
        return sb.ToString();
    }

    private static void Line(StringBuilder sb, string text) => sb.Append(text).Append('\n');
}
